
import re


UNSUPPORTED_CITATION = re.compile(
    r"【[^】]+】"
)


def validate_citations(answer):
    """
    Detect unsupported citation markers generated by the LLM.
    This does not verify whether URLs support factual claims.
    """
    markers = UNSUPPORTED_CITATION.findall(answer)

    cleaned_answer = UNSUPPORTED_CITATION.sub(
        "",
        answer
    )

    return {
        "valid": len(markers) == 0,
        "unsupported_markers": markers,
        "cleaned_answer": cleaned_answer.strip()
    }
